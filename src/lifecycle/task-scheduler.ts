import { execFileSync } from "node:child_process";
import { logPaths, TASK_NAME } from "./constants";

/**
 * Windows backend for the Supervisor interface. Wraps Windows Task Scheduler
 * cmdlets via powershell.exe. Counterpart of launchd.ts for macOS.
 *
 * Task Scheduler has no equivalent of launchd's KeepAlive: SuccessfulExit=false,
 * so the marker-suppression mechanism (used by the shim on macOS) is not needed
 * here. When dev exits cleanly, the prod task simply remains stopped until
 * `tb-streamer service start` (or system reboot, if the task is at-logon-triggered).
 */
function ps(command: string): string {
  return execFileSync("powershell.exe", ["-NoProfile", "-NonInteractive", "-Command", command], {
    stdio: ["ignore", "pipe", "ignore"],
  }).toString();
}

function psSafe(command: string): void {
  try {
    ps(command);
  } catch {
    // Intentionally swallowed — caller is one of the stop/disable variants where
    // "already gone" is the desired state.
  }
}

export function isAgentLoaded(): boolean {
  // A disabled task is what bootoutAgent() leaves behind, so it counts as not
  // loaded — the same answer launchd gives after a bootout. Treating it as
  // loaded sent `service start` down the kickstart path, whose
  // Start-ScheduledTask fails on a disabled task.
  try {
    const state = ps(`(Get-ScheduledTask -TaskName '${TASK_NAME}' -ErrorAction Stop).State`);
    return state.trim() !== "Disabled";
  } catch {
    return false;
  }
}

/**
 * Kill the prod server's process tree. Stop-ScheduledTask cannot do this: the
 * task's action is wscript -> launch.vbs, which spawns a hidden cmd -> node and
 * exits at once, so the task instance is already over (State `Ready`) while the
 * server runs on outside it. Matched by command line, not by port, so a dev
 * instance holding 8766 is never touched; `/T` takes the PTY children with it.
 */
function killProdServer(): void {
  psSafe(
    `Get-CimInstance Win32_Process -Filter "Name='node.exe'" ` +
      `| Where-Object { $_.CommandLine -like '*cli.js*serve*' -and $_.CommandLine -like '*--prod*' -and $_.ProcessId -ne ${process.pid} } ` +
      `| ForEach-Object { taskkill.exe /PID $_.ProcessId /T /F | Out-Null; Wait-Process -Id $_.ProcessId -Timeout 10 -ErrorAction SilentlyContinue }`,
  );
}

export function bootoutAgent(): void {
  // Stop running instance + disable trigger. Mirrors macOS bootout semantics:
  // the task stays registered but will not run again until bootstrap.
  psSafe(`Stop-ScheduledTask -TaskName '${TASK_NAME}' -ErrorAction SilentlyContinue`);
  killProdServer();
  psSafe(`Disable-ScheduledTask -TaskName '${TASK_NAME}' -ErrorAction SilentlyContinue | Out-Null`);
}

export function bootstrapAgent(_specPath: string, _opts?: { afterBootout?: boolean }): void {
  // _specPath is the plist path on macOS; ignored on Windows because the task
  // is already registered by scripts\deploy.ps1 setup. The caller is asking
  // us to re-enable + start it. _opts.afterBootout is macOS-specific (exit 5
  // race tolerance) and has no effect here.
  ps(`Enable-ScheduledTask -TaskName '${TASK_NAME}' -ErrorAction Stop | Out-Null`);
  ps(`Start-ScheduledTask -TaskName '${TASK_NAME}' -ErrorAction Stop`);
}

export function kickstartAgent(): void {
  psSafe(`Stop-ScheduledTask -TaskName '${TASK_NAME}' -ErrorAction SilentlyContinue`);
  killProdServer();
  ps(`Start-ScheduledTask -TaskName '${TASK_NAME}' -ErrorAction Stop`);
}

/**
 * Returns the absolute paths to the streamer's stdout/stderr log files.
 *
 * Task Scheduler has no native stdout/stderr redirection, so the launch.cmd
 * generated by scripts/deploy.ps1 carries it as cmd `>>` targets. Those targets
 * are these paths — both sides read them from `logPaths()`, which is what keeps
 * the launcher and `prod logs` from drifting apart.
 */
export function getLogPaths(): { stdout: string; stderr: string } {
  return logPaths();
}

export function getAgentPid(): number | null {
  // Task Scheduler does not expose the running PID directly. WMI is the
  // best-available probe: find node.exe processes whose command line
  // mentions "cli.js serve". Returns the first match, or null.
  try {
    const out = ps(
      `(Get-CimInstance Win32_Process -Filter "Name='node.exe'" ` +
        `| Where-Object { $_.CommandLine -like '*cli.js*serve*' } ` +
        `| Select-Object -First 1 -ExpandProperty ProcessId)`,
    ).trim();
    const n = Number.parseInt(out, 10);
    return Number.isFinite(n) && n > 0 ? n : null;
  } catch {
    return null;
  }
}
